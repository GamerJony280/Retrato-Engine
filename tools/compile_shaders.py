#!/usr/bin/env python3
"""Optional authoring tool. Runtime and normal builds do not require Python/glslang."""
import argparse, hashlib, os, subprocess, tempfile
from pathlib import Path
root=Path(__file__).resolve().parents[1]
def main():
    parser=argparse.ArgumentParser();parser.add_argument('--compiler',default='glslangValidator');args=parser.parse_args()
    dest=root/'shaders/precompiled';dest.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory() as temp:
        cache=Path(temp);lines=['# Regenerated by tools/compile_shaders.py.']
        for stage in ['vert','frag']:
            source=root/('shaders/scene.'+stage);out=cache/('scene.'+stage+'.spv')
            subprocess.run([args.compiler,'-V',str(source),'-o',str(out)],check=True)
            for label,path in [('SOURCE',source),('SPIRV',out)]:
                lines.append('set(RETRATO_'+stage.upper()+'_'+label+'_SHA256 "'+hashlib.sha256(path.read_bytes()).hexdigest()+'")')
        for stage in ['vert','frag']:
            path=dest/('scene.'+stage+'.spv');pending=path.with_suffix('.pending');pending.write_bytes((cache/path.name).read_bytes());os.replace(pending,path)
        pending=dest/'hashes.pending';pending.write_text('\n'.join(lines)+'\n');os.replace(pending,dest/'hashes.cmake')
if __name__=='__main__':main()
