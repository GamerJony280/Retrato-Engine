function start()
    engine.clear()
    local object=engine.box(0,0,0,2,2,2,1,1,1)
    local collider=engine.collider(object)
    local distance,x,y,z,nx,ny,nz=engine.raycast(collider,0,0,-4,0,0,1,10)
    assert(math.abs(distance-3)<0.0001)
    assert(math.abs(z+1)<0.0001)
    engine.position(object,0,0,2)
    distance=engine.raycast(collider,0,0,-4,0,0,1,10)
    assert(math.abs(distance-5)<0.0001)
    assert(engine.raycast(collider,5,0,-4,0,0,1,10)==nil)
    assert(not pcall(engine.position,999,0,0,0))
    local stale_object, stale_collider = object, collider
    engine.clear()
    local replacement = engine.box(0,0,0,1,1,1,1,1,1)
    assert(not pcall(engine.position,stale_object,0,0,0))
    assert(not pcall(engine.raycast,stale_collider,0,0,-4,0,0,1,10))
    engine.position(replacement,1,0,0)
    engine.destroy(replacement)
    assert(not pcall(engine.position,replacement,0,0,0))
    engine.save_set_int("health", 77)
    engine.save_set_float("speed", 2.5)
    engine.save_set_bool("alive", true)
    engine.save_set_string("name", "lua-player")
    engine.save_set_vec3("spawn", 1, 2, 3)
    engine.save_write("lua-test.embsave")
    engine.save_clear()
    engine.save_read("lua-test.embsave")
    local sx, sy, sz = engine.save_get_vec3("spawn")
    assert(engine.save_has("health") and engine.save_get_int("health") == 77)
    assert(engine.save_get_float("speed") == 2.5 and engine.save_get_bool("alive"))
    assert(engine.save_get_string("name") == "lua-player" and sx == 1 and sy == 2 and sz == 3)
    print("PASS: Lua handles, destruction, save data, collider, moving transform, raycast and errors")
end
